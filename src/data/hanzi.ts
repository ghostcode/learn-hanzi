export const COMMON = build([...commonRows, ...commonBulkRows], 'common')
export const UNCOMMON = build([...uncommonRows, ...uncommonBulkRows], 'uncommon')
export const RARE = build(rareRows, 'rare')

export const ALL_HANZI: Hanzi[] = [...COMMON, ...UNCOMMON, ...RARE]

export function getByCategory(category: Category): Hanzi[] {
  return ALL_HANZI.filter((h) => h.category === category)
}

export function getByChar(char: string): Hanzi | undefined {
  return ALL_HANZI.find((h) => h.char === char)
}

export function search(query: string): Hanzi[] {
  const q = query.trim().toLowerCase()
  if (!q) return []
  return ALL_HANZI.filter(
    (h) =>
      h.char.includes(q) ||
      h.pinyin.toLowerCase().includes(q) ||
      h.meanings.some((m) => m.includes(q)) ||
      h.words.some((w) => w.includes(q)),
  )
}
