/**
 * 数据以紧凑元组编写，build 统一补全分类字段。
 * 元组顺序：[字, 拼音, 部首, 笔画, 结构, 释义[], 组词[], 成语?]
 */
export type Row = [
  char: string,
  pinyin: string,
  radical: string,
  strokes: number,
  structure: string,
  meanings: string[],
  words: string[],
  idioms?: string[],
]

function build(rows: Row[], category: Category): Hanzi[] {
  return rows.map(
    ([char, pinyin, radical, strokes, structure, meanings, words, idioms]) => ({
      char,
      pinyin,
      radical,
      strokes,
      structure,
      meanings,
      words,
      idioms,
      category,
    }),
  )
}

